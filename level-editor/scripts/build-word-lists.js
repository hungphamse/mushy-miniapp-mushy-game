import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const SOURCE_DIR = resolve('scripts', 'wordlist-sources');
const OUTPUT_FILE = resolve('src', 'lib', 'data', 'wordLists.js');
const LENGTHS = [4, 5, 6, 7, 8];

const LEGACY_SOURCE_FILES = {
  answers: [resolve(SOURCE_DIR, 'scowl-10.txt')],
  guesses: [resolve(SOURCE_DIR, 'scowl-american-50.txt'), resolve(SOURCE_DIR, 'scowl-british-50.txt'), resolve(SOURCE_DIR, 'scowl-english-50.txt')],
};

const BLOCKLIST_FILE = resolve(SOURCE_DIR, 'ldnoobwv2-en.txt');

function discoverSourceGroup(prefix, fallbackFiles) {
  if (!existsSync(SOURCE_DIR)) {
    return fallbackFiles;
  }

  const discovered = readdirSync(SOURCE_DIR)
    .filter((name) => (
      name === `${prefix}.txt` ||
      (name.startsWith(`${prefix}-`) && name.endsWith('.txt'))
    ))
    .sort((left, right) => left.localeCompare(right))
    .map((name) => resolve(SOURCE_DIR, name));

  return discovered.length > 0 ? discovered : fallbackFiles;
}

function discoverSourceFiles() {
  return {
    answers: discoverSourceGroup('scowl-answers', LEGACY_SOURCE_FILES.answers),
    guesses: discoverSourceGroup('scowl-valid-guesses', LEGACY_SOURCE_FILES.guesses),
    blocklist: BLOCKLIST_FILE,
  };
}

export function cleanWord(rawWord) {
  const word = rawWord.trim();

  if (shouldRemoveRawWord(word)) {
    return null;
  }

  const normalized = word.toUpperCase();
  return /^[A-Z]+$/.test(normalized) ? normalized : null;
}

function loadWords(filePath) {
  return readFileSync(filePath, 'utf8')
    .split(/\r?\n/)
    .map((word) => cleanWord(word))
    .filter(Boolean);
}

function shouldRemoveRawWord(word) {
  return isNameLike(word) || isPossessiveForm(word);
}

function isNameLike(word) {
  return /^[A-Z][A-Za-z]*$/.test(word);
}

function isPossessiveForm(word) {
  return /^[A-Za-z]+'s$/.test(word);
}

function uniqueSorted(words) {
  return [...new Set(words)].sort((left, right) => left.localeCompare(right));
}

function sourceNames(files) {
  return files.map((filePath) => basename(filePath)).join(', ');
}

function assertSourceFilesExist(sourceFiles) {
  const requiredFiles = [
    ...sourceFiles.answers.map((filePath) => ['answer', filePath]),
    ...sourceFiles.guesses.map((filePath) => ['valid guess', filePath]),
    ['blocklist', sourceFiles.blocklist],
  ];

  for (const [name, filePath] of requiredFiles) {
    try {
      readFileSync(filePath, 'utf8');
    } catch {
      throw new Error(
        `Missing ${name} source file at ${filePath}. Add SCOWL/profanity sources before running wordlists:build.`,
      );
    }
  }
}

function loadMergedWords(filePaths) {
  return uniqueSorted(filePaths.flatMap((filePath) => loadWords(filePath)));
}

function buildLists() {
  const sourceFiles = discoverSourceFiles();
  assertSourceFilesExist(sourceFiles);

  const answerSource = loadMergedWords(sourceFiles.answers);
  const guessSource = loadMergedWords(sourceFiles.guesses);
  const blocklist = new Set(loadWords(sourceFiles.blocklist));

  const ANSWER_LISTS = {};
  const VALID_GUESS_LISTS = {};

  for (const length of LENGTHS) {
    const answers = uniqueSorted(
      answerSource
        .filter((word) => word.length === length)
        .filter((word) => !blocklist.has(word)),
    );

    const guesses = uniqueSorted([
      ...guessSource.filter((word) => word.length === length),
      ...answers,
    ]);

    if (answers.length === 0) {
      throw new Error(`No answer words generated for length ${length}`);
    }

    if (guesses.length === 0) {
      throw new Error(`No valid guesses generated for length ${length}`);
    }

    ANSWER_LISTS[length] = answers;
    VALID_GUESS_LISTS[length] = guesses;
  }

  return { ANSWER_LISTS, VALID_GUESS_LISTS, sourceFiles };
}

function renderModule({ ANSWER_LISTS, VALID_GUESS_LISTS, sourceFiles }) {
  const generatedDate = new Date().toISOString().slice(0, 10);

  return `// AUTO-GENERATED by scripts/build-word-lists.js. DO NOT EDIT MANUALLY.
// Answer sources: ${sourceNames(sourceFiles.answers)}
// Valid guess sources: ${sourceNames(sourceFiles.guesses)}
// Answer blocklist: ${basename(sourceFiles.blocklist)}
// Last generated: ${generatedDate}

export const ANSWER_LISTS = ${JSON.stringify(ANSWER_LISTS, null, 2)};

export const VALID_GUESS_LISTS = ${JSON.stringify(VALID_GUESS_LISTS, null, 2)};

export const ALL_ANSWERS_FLAT = Object.values(ANSWER_LISTS).flat();
`;
}

function writeWordLists() {
  const lists = buildLists();

  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, renderModule(lists));

  for (const length of LENGTHS) {
    console.log(
      `Length ${length}: ${lists.ANSWER_LISTS[length].length} answers, ` +
      `${lists.VALID_GUESS_LISTS[length].length} valid guesses`,
    );
  }

  console.log(`\n${OUTPUT_FILE} written.`);
  console.log(`Answer sources: ${sourceNames(lists.sourceFiles.answers)}`);
  console.log(`Valid guess sources: ${sourceNames(lists.sourceFiles.guesses)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeWordLists();
}
